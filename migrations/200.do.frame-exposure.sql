-- TASK-532: полоса настроек съёмки (doc-02, макет `FrameInfo`) — чувствительность,
-- экспозиция и выдержка. До них «Сведения о кадре» отдавали половину полосы: карточку
-- техники венчали объектив и диафрагма, а ISO, ev и время выдержки рисовать было
-- нечем.
--
-- Три колонки рядом с `focal_length_mm` и `aperture` — того же происхождения: их
-- читает montage-воркер из метаданных оригинала и записывает сюда тем же `update`,
-- каким пишет `width`, `height` и `camera_model`. API их только отдаёт.
--
-- Имена в стиле соседних, без единиц в имени: `iso`, `exposure_ev`, `shutter`.
-- Обратной совместимости нет (decision-19) — база и хранилище сносятся перед
-- следующим деплоем, поэтому веток «а что если попадётся старая строка» здесь не
-- бывает, а колонка добавляется обычной миграцией.
--
-- Idempotent (see README «Миграции»): отметка о версии пишется отдельным запросом,
-- и процесс, убитый между ними, проигрывает этот файл заново.
--
-- Номер оставляет разрыв, как 010…190: вехи пишутся параллельно по одному
-- репозиторию, а две миграции с одной версией — это конфликт, который уже не
-- разрешить после того, как применена хоть одна.

-- Чувствительность в том виде, в каком она стоит в EXIF: `100`, `400`, `12800`.
-- `double precision`, а не `integer`, по той же причине, что `focal_length_mm` рядом:
-- соседние колонки об измерениях съёмки держат одно число, и целочисленный тип здесь
-- обрёл бы точность, которой в метаданных нет, — а ошибкой обошёлся бы воркеру,
-- пишущему `update` с числом, которое вдруг оказалось дробным.
ALTER TABLE media_items ADD COLUMN IF NOT EXISTS iso double precision;

-- Экспозиция в ступенях: `0`, `+0.7`, `-1.3`. Ноль здесь — настоящий ноль, «съёмка
-- без компенсации», и его нельзя спутать с «воркер не смотрел»: поэтому колонка
-- nullable и **без** `DEFAULT 0`, который стёр бы разницу при первом же INSERT.
ALTER TABLE media_items ADD COLUMN IF NOT EXISTS exposure_ev double precision;

-- Выдержка — дробью текстом, ровно тем текстом, что лежит в EXIF: `1/60`, `1/1`,
-- `0.5`. Не числом секунд и сознательно: макет обещает «1/60 с», а из `0.0166…`
-- телефон обратно угадывал бы знаменатель, и на `1/125` нарисовал бы «0.008 с».
-- Единицу в строке ставит приложение на языке читателя, как и у диафрагмы.
ALTER TABLE media_items ADD COLUMN IF NOT EXISTS shutter text;
