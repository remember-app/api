-- m-32 Frame comments (TASK-497): что человек пишет под кадром — подписать, что
-- здесь происходит, назвать людей (doc-14). Комментарий виден всем, кто видит
-- кадр, и уходит вместе с ним; режиссёр монтажа читает их как контекст при
-- сборке ролика. Контракт — docs/media.md.
-- Idempotent (see README «Миграции»): отметка о версии пишется отдельным
-- запросом, и процесс, убитый между ними, проигрывает этот файл заново.
--
-- Номер оставляет разрыв, как 010…180: вехи пишутся параллельно по одному
-- репозиторию, а две миграции с одной версией — это конфликт, который уже не
-- разрешить после того, как применена хоть одна. Обратной совместимости нет
-- (decision-19): веток «а что если попадётся старая строка» здесь не бывает.

CREATE TABLE IF NOT EXISTS frame_comments (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  media_id   uuid NOT NULL,
  -- Денормализовано ради составной ссылки ниже: вдвоём с ней это и есть «комментарий
  -- не выходит за своё воспоминание» — не обещание маршрута, а то, чего база просто не
  -- даст записать. Устройство то же, что у `label_media` (миграция 120).
  memory_id  uuid NOT NULL REFERENCES memories (id) ON DELETE CASCADE,
  -- Кто написал. Каскад тот же и по той же причине, что у media_items.uploaded_by:
  -- не стало учётной записи — не стало и того, что человек в ней оставил. Человек же
  -- уходит из воспоминания, учётная запись у него остаётся: такие комментарии стоят
  -- на месте (см. handOver, `src/media/comments.ts`).
  author_id  uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  -- Подпись под кадром, а не документ: полстраницы хватает сказать всё, что режиссёру
  -- о кадре нужно знать. Потолок стоит и здесь, и в схеме маршрута: в базе он держит
  -- колонку от всего, что мимо маршрута, в схеме превращает чужую ошибку в 400, а не 500.
  -- `btrim`, а не `char_length(body)`: пробелы по краям срезает маршрут, и «   » — это
  -- пустой комментарий, а не комментарий из трёх символов.
  body       text NOT NULL CHECK (char_length(btrim(body)) BETWEEN 1 AND 500),
  created_at timestamptz NOT NULL DEFAULT now(),
  -- Удалённый кадр уносит свои комментарии сам — поштучно или уходом участника, — и в
  -- коде удаления на это нет ни строки (src/media/gallery.ts, removeMedia). Уникальный
  -- индекс (id, memory_id) на media_items завела миграция 120, он же цель этой ссылки.
  FOREIGN KEY (media_id, memory_id) REFERENCES media_items (id, memory_id) ON DELETE CASCADE
);

-- Ровно тот отбор, которым читается список: комментарии одного кадра по времени.
CREATE INDEX IF NOT EXISTS frame_comments_media_idx ON frame_comments (media_id, created_at);
